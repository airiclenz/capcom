package clidoc

import (
	"bytes"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"

	"github.com/airiclenz/capcom/internal/cli"
)

// committedReferenceDir is the committed CLI reference, relative to this package's directory.
const committedReferenceDir = "../../docs/site/reference/cli"

// markdownLink matches a Markdown link and captures its target.
var markdownLink = regexp.MustCompile(`\]\(([^)]*)\)`)

// pageFrontmatter is the frontmatter every reference page opens with.
type pageFrontmatter struct {
	Title       string `yaml:"title"`
	Description string `yaml:"description"`
	Sidebar     *struct {
		Order *int `yaml:"order"`
	} `yaml:"sidebar"`
}

func TestWriteReference_WritesOnePagePerCommand(t *testing.T) {
	dir := t.TempDir()
	if err := WriteReference(cli.Command(), dir); err != nil {
		t.Fatalf("WriteReference: %v", err)
	}

	for _, name := range []string{"capcom.md", "capcom_ready.md", "capcom_know_add.md", "capcom_prime.md"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Errorf("expected page %s: %v", name, err)
		}
	}
	for _, name := range []string{"capcom_help.md", "capcom_completion.md", "capcom_know_help.md"} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			t.Errorf("unexpected page %s", name)
		}
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read %s: %v", dir, err)
	}
	for _, entry := range entries {
		name := entry.Name()
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatalf("read %s: %v", name, err)
		}
		text := string(data)
		if !strings.HasPrefix(text, "---\ntitle:") {
			t.Errorf("%s: does not open with frontmatter and its title", name)
		}
		if strings.Contains(text, "Auto generated by spf13/cobra") {
			t.Errorf("%s: carries cobra's auto-generated date line", name)
		}
		checkFrontmatter(t, name, text)
		for _, link := range markdownLink.FindAllStringSubmatch(text, -1) {
			if strings.ContainsAny(link[1], `/\`) || !strings.HasSuffix(link[1], markdownExtension) {
				t.Errorf("%s: link %q is not a bare .md file name", name, link[1])
			}
		}
	}
}

// checkFrontmatter parses the YAML between the page's opening and closing `---` lines and reports
// a parse failure or a missing title, description or sidebar order.
func checkFrontmatter(t *testing.T, name, text string) {
	t.Helper()
	body, ok := strings.CutPrefix(text, "---\n")
	if !ok {
		return
	}
	block, _, ok := strings.Cut(body, "\n---\n")
	if !ok {
		t.Errorf("%s: frontmatter is not closed", name)
		return
	}
	var front pageFrontmatter
	if err := yaml.Unmarshal([]byte(block), &front); err != nil {
		t.Errorf("%s: frontmatter does not parse: %v", name, err)
		return
	}
	if front.Title == "" || front.Description == "" {
		t.Errorf("%s: frontmatter lacks a title or description: %+v", name, front)
	}
	if front.Sidebar == nil || front.Sidebar.Order == nil {
		t.Errorf("%s: frontmatter lacks sidebar.order", name)
	}
	if want := strings.ReplaceAll(strings.TrimSuffix(name, markdownExtension), "_", " "); front.Title != want {
		t.Errorf("%s: title %q, want %q", name, front.Title, want)
	}
}

func TestReferenceUpToDate(t *testing.T) {
	fresh := t.TempDir()
	if err := WriteReference(cli.Command(), fresh); err != nil {
		t.Fatalf("WriteReference: %v", err)
	}
	want := readPages(t, fresh)
	got := readPages(t, committedReferenceDir)

	for name, wantData := range want {
		gotData, ok := got[name]
		switch {
		case !ok:
			t.Errorf("%s: missing from %s", name, committedReferenceDir)
		case !bytes.Equal(gotData, wantData):
			t.Errorf("%s: differs from a fresh generation", name)
		}
	}
	for name := range got {
		if _, ok := want[name]; !ok {
			t.Errorf("%s: no command generates this page", name)
		}
	}
	if t.Failed() {
		t.Log("the committed CLI reference is stale: run `go run ./cmd/gendocs` and commit the result")
	}
}

// readPages returns the contents of every file in dir, keyed by file name.
func readPages(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("read %s: %v", dir, err)
	}
	pages := make(map[string][]byte, len(entries))
	for _, entry := range entries {
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			t.Fatalf("read %s: %v", entry.Name(), err)
		}
		pages[entry.Name()] = data
	}
	return pages
}
